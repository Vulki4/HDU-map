function room(id, label, labelKk, [x, y, right, bottom], type = 'room') {
  return { id, label, labelKk, type, x, y, w: right - x, h: bottom - y, cx: (x + right) / 2, cy: (y + bottom) / 2 };
}

function polygon(id, label, labelKk, points, cx, cy, type) {
  return { id, label, labelKk, points, cx, cy, type };
}

